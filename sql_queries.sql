-- Question 10: Average time taken to ship orders by quarter
SELECT
    quarter_number,
    ROUND(AVG(julianday(ship_date) - julianday(order_date)), 2) AS avg_days_to_ship
FROM order_t
GROUP BY quarter_number
ORDER BY quarter_number;
